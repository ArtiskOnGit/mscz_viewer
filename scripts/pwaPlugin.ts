// PWA build (ADR-027): `vite build --mode pwa` → dist-pwa/, served under /mscz_viewer/ on GitHub Pages.
// This plugin, active in that mode only:
// - adds the web app manifest, the iOS home screen tags and the theme colours to index.html;
// - writes manifest.webmanifest, 404.html (GitHub Pages serves it for deep links: a copy of index.html, the router
//   then reads the URL) and sw.js: src/pwa/sw.js preceded by the list of EVERY file of the build with its hash and
//   size (the service worker precaches all of it, ~45 MB, so that import, rendering and sound work offline).
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

export const PWA_BASE = '/mscz_viewer/';
const THEME = '#24398f';
const BACKGROUND = '#f4ecd8';

/** Files never precached: the service worker itself and the GitHub Pages fallback (index.html is served instead). */
const EXCLUDED = new Set(['sw.js', '404.html']);

async function listFiles(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await listFiles(path)));
    else out.push(path);
  }
  return out;
}

export function pupitrePwa(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'pupitre-pwa',
    apply: (_, env) => env.command === 'build' && env.mode === 'pwa',
    configResolved(c) {
      config = c;
    },
    transformIndexHtml() {
      const b = config.base;
      return [
        { tag: 'link', attrs: { rel: 'manifest', href: `${b}manifest.webmanifest` }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'theme-color', content: THEME }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'apple-touch-icon', href: `${b}icons/apple-touch-icon.png` }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'apple-mobile-web-app-capable', content: 'yes' }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'mobile-web-app-capable', content: 'yes' }, injectTo: 'head' },
        // "default": the status bar keeps its own band (no content under it, readable in light and dark themes).
        { tag: 'meta', attrs: { name: 'apple-mobile-web-app-status-bar-style', content: 'default' }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'apple-mobile-web-app-title', content: 'Pupitre' }, injectTo: 'head' },
      ];
    },
    async closeBundle() {
      const out = config.build.outDir;
      const b = config.base;
      const manifest = {
        name: 'Pupitre',
        short_name: 'Pupitre',
        description: 'Offline MuseScore score viewer for rehearsing musicians',
        id: b,
        start_url: b,
        scope: b,
        display: 'standalone',
        orientation: 'any',
        theme_color: THEME,
        background_color: BACKGROUND,
        lang: 'en',
        icons: [
          { src: `${b}icons/icon-192.png`, sizes: '192x192', type: 'image/png', purpose: 'any' },
          { src: `${b}icons/icon-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any' },
          { src: `${b}icons/icon-maskable-512.png`, sizes: '512x512', type: 'image/png', purpose: 'maskable' },
          { src: `${b}favicon.svg`, sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
        ],
      };
      await writeFile(join(out, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));
      await writeFile(join(out, '404.html'), await readFile(join(out, 'index.html')));

      const entries: [path: string, revision: string, size: number][] = [];
      for (const file of (await listFiles(out)).sort()) {
        const path = relative(out, file).split(sep).join('/');
        if (EXCLUDED.has(path) || path.endsWith('.map')) continue;
        const bytes = await readFile(file);
        entries.push([path, createHash('sha256').update(bytes).digest('hex').slice(0, 16), bytes.length]);
      }
      const build = createHash('sha256').update(JSON.stringify(entries)).digest('hex').slice(0, 12);
      const template = await readFile(new URL('../src/pwa/sw.js', import.meta.url), 'utf8');
      const header = `// Generated by scripts/pwaPlugin.ts (version ${JSON.stringify(process.env.npm_package_version ?? '')}).\n`
        + `self.__PUPITRE_BUILD = ${JSON.stringify(build)};\nself.__PUPITRE_PRECACHE = ${JSON.stringify(entries)};\n`;
      await writeFile(join(out, 'sw.js'), header + template);
      const total = entries.reduce((s, e) => s + e[2], 0);
      config.logger.info(`pupitre-pwa: sw.js precaches ${entries.length} files, ${(total / 1e6).toFixed(1)} MB (build ${build})`);
    },
  };
}
